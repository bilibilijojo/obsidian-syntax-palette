"""Build a color-only snippet from the checked-in upstream theme definitions."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EDITOR = ('.markdown-source-view.mod-cm6 '
          '.cm-line.HyperMD-codeblock:not(.HyperMD-codeblock-begin)'
          ':not(.HyperMD-codeblock-end) .cm-hmd-codeblock')
# Native Obsidian gives language classes to syntax-highlighted fenced code.
# Untagged/indented pre blocks have no such class and are deliberately excluded.
READING = '.markdown-rendered .el-pre > pre:not(.frontmatter) > code[class*="language-"]'

def palette(mode):
    theme = json.loads((ROOT / f'sources/One{mode}.json').read_text())
    def scope_color(scope):
        colors = []
        for rule in theme['tokenColors']:
            scopes = rule.get('scope', [])
            if isinstance(scopes, str):
                scopes = [s.strip() for s in scopes.split(',')]
            if scope in scopes and 'foreground' in rule['settings']:
                colors.append(rule['settings']['foreground'])
        assert colors, scope
        return colors[-1]
    return {
        'normal': theme['colors']['editor.foreground'],
        **{name: scope_color(scope) for name, scope in {
            'comment': 'comment', 'keyword': 'keyword', 'number': 'constant.numeric',
            'string': 'string', 'function': 'entity.name.function',
            'class': 'entity.name.class', 'variable': 'variable',
            'attribute': 'entity.other.attribute-name', 'builtin': 'support.function',
            'operator': 'keyword.operator', 'regex': 'string.regexp',
            'css-fallback': 'source.css property-name',
        }.items()},
    }

parts = ['''/*
 * Atom One syntax only — Obsidian 1.14.4 / Minimal 9.1.4
 * Generated by tools/build_snippet.py from the upstream JSON snapshots.
 * Sources:
 * https://github.com/akamud/vscode-theme-onelight/blob/master/themes/OneLight.json
 * https://github.com/akamud/vscode-theme-onedark/blob/master/themes/OneDark.json
 *
 * Only color and private --aos-* color variables are declared.
 * No global Obsidian/Minimal variables, backgrounds, typography or layout.
 * CodeMirror uses stable named classes; no generated .cm-xxxx classes.
 * Token categories are an approximation of TextMate: see README.md.
 * Unlabelled code and indented code in reading view are intentionally untouched.
 */
''']
for mode in ['Light', 'Dark']:
    selector = f'.theme-{mode.lower()}'
    parts.append(f'{selector} {EDITOR},\n{selector} {READING} {{')
    parts.extend(f'  --aos-{key}: {value};' for key, value in palette(mode).items())
    parts.append('}\n')

def rule(selectors, color, comment=None):
    if comment:
        parts.append(f'/* {comment} */')
    parts.append(',\n'.join(selectors) + ' {\n  color: var(--aos-' + color + ');\n}\n')

rule([f':is(.theme-light, .theme-dark) {EDITOR}',
      f':is(.theme-light, .theme-dark) {READING}'], 'normal',
     'Base text inside the fence; fence delimiters and language labels are excluded.')

# Both source mode and Live Preview use the same native CM6 syntax classes.
for names, color in [
    (['comment', 'meta'], 'comment'),
    (['keyword'], 'keyword'),
    (['number', 'atom'], 'number'),
    (['string', 'string-2'], 'string'),
    (['variable', 'variable-2', 'property'], 'normal'),
    (['variable-3', 'type'], 'class'),
    (['def'], 'function'),
    (['builtin'], 'builtin'),
    (['operator'], 'operator'),
    (['punctuation', 'bracket'], 'normal'),
    (['tag'], 'variable'),
    (['attribute'], 'attribute'),
    (['qualifier'], 'variable'),
]:
    rule([f'{EDITOR}.cm-{name}' for name in names], color)

rule([f'{EDITOR}.cm-string.cm-property'], 'variable',
     'CodeMirror marks quoted JSON/JavaScript keys with both classes.')
rule([f'{EDITOR}.cm-tag.cm-bracket'], 'normal',
     'HTML tag delimiters are punctuation, not tag names.')

# Prism spans inherit only the private palette from their own code element.
for names, color in [
    (['comment', 'prolog', 'doctype', 'cdata'], 'comment'),
    (['keyword', 'atrule'], 'keyword'),
    (['number', 'boolean', 'constant'], 'number'),
    (['string', 'char', 'attr-value', 'inserted'], 'string'),
    (['function', 'function-variable'], 'function'),
    (['class-name'], 'class'),
    (['builtin', 'entity', 'symbol', 'regex', 'url'], 'builtin'),
    (['tag', 'variable', 'property', 'selector', 'deleted'], 'variable'),
    (['attr-name'], 'attribute'),
    (['parameter', 'property-access', 'punctuation'], 'normal'),
    (['operator'], 'operator'),
    (['important'], 'keyword'),
]:
    rule([f'{READING} .token.{name}' for name in names], color)

rule([f'{READING} .token.regex'], 'regex')
rule([f'{READING} .token.function.property-access'], 'function',
     'Prism marks method calls as both function and property-access.')
rule([f'{READING} .token.attr-value .token.punctuation'], 'string',
     'HTML attribute quotes belong to the string; keep tag brackets normal.')
rule([f'{READING} .token.attr-value > .token.punctuation.attr-equals'], 'normal')
rule([f'{READING} .token.tag > .token.punctuation'], 'normal')
rule([f'{READING} .token.template-punctuation'], 'string')
rule([f'{READING} .token.interpolation > .token.interpolation-punctuation'], 'variable')

def reading_language(langs, token, color):
    rule([f'{READING}.language-{lang} .token.{token}' for lang in langs], color)

reading_language(['javascript', 'js', 'typescript', 'ts'], 'operator', 'builtin')
reading_language(['json'], 'property', 'variable')
reading_language(['json'], 'boolean', 'builtin')
reading_language(['json'], 'null', 'builtin')
reading_language(['css'], 'property', 'normal')
reading_language(['css'], 'selector', 'variable')
reading_language(['css'], 'string', 'string')
reading_language(['css'], 'attr-name', 'attribute')
# Embedded <style> uses Prism's .language-css on a descendant token.
rule([f'{READING} .language-css .token.property'], 'normal')
rule([f'{READING} .language-css .token.selector'], 'variable')

(ROOT / 'atom-one-syntax.css').write_text('\n'.join(parts))
(ROOT / 'sources/palette.json').write_text(json.dumps(
    {mode.lower(): palette(mode) for mode in ['Light', 'Dark']}, indent=2) + '\n')
